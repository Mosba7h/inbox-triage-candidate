"""One-shot eval: triage all tickets with the live model, score against labels.

    python -m triage.evaluate

Writes:
  eval/results.json  - metrics + one prediction per ticket (the requested shape)
  eval/details.json  - same predictions plus diagnostics (source, flags, attempts, latency)
  eval/report.md     - human-readable metrics, confusion matrices, every miss
"""

from __future__ import annotations

import json
import logging
import sys
import time
from collections import Counter
from pathlib import Path

from .batch import load_tickets, run_batch
from .config import load_settings
from .llm import OpenAICompatibleModel
from .schema import CATEGORIES, PRIORITIES, PRIORITY_RANK, TriageResult

log = logging.getLogger("triage.eval")


def load_labels(path: Path) -> dict[str, dict]:
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    items = data["labels"] if isinstance(data, dict) else data
    return {x["id"]: x for x in items}


def compute_metrics(results: list[TriageResult], labels: dict[str, dict]) -> dict:
    scored = [r for r in results if r.id in labels]
    n = len(scored)
    cat_hits = [r for r in scored if r.category == labels[r.id]["category"]]
    pri_hits = [r for r in scored if r.priority == labels[r.id]["priority"]]
    pri_near = [r for r in scored if abs(PRIORITY_RANK[r.priority] - PRIORITY_RANK[labels[r.id]["priority"]]) <= 1]
    cat_ok = {r.id for r in cat_hits}
    both = [r for r in pri_hits if r.id in cat_ok]
    auto = [r for r in scored if not r.escalate]

    def avg(xs):
        return round(sum(xs) / len(xs), 3) if xs else None

    return {
        "category_accuracy": round(len(cat_hits) / n, 3) if n else 0.0,
        "priority_agreement": round(len(pri_hits) / n, 3) if n else 0.0,
        "priority_within_one_level": round(len(pri_near) / n, 3) if n else 0.0,
        "both_correct": round(len(both) / n, 3) if n else 0.0,
        "n_labeled": n,
        "n_predictions": len(results),
        "escalation_rate": round(sum(r.escalate for r in results) / len(results), 3) if results else 0.0,
        # Is confidence telling us anything? Compare on the labeled subset.
        "mean_confidence_category_correct": avg([r.confidence for r in cat_hits]),
        "mean_confidence_category_wrong": avg([r.confidence for r in scored if r.id not in cat_ok]),
        "category_accuracy_not_escalated": round(sum(r.id in cat_ok for r in auto) / len(auto), 3) if auto else None,
        "n_labeled_not_escalated": len(auto),
    }


def _confusion(results, labels, field, values) -> str:
    scored = [r for r in results if r.id in labels]
    counts = Counter((labels[r.id][field], getattr(r, field)) for r in scored)
    head = "| gold \\ pred | " + " | ".join(values) + " |\n|---|" + "---|" * len(values) + "\n"
    rows = ""
    for g in values:
        if not any(counts[(g, p)] for p in values):
            continue
        rows += f"| **{g}** | " + " | ".join(str(counts[(g, p)] or "") for p in values) + " |\n"
    return head + rows


def write_report(path: Path, results, labels, metrics, run_stats, tickets) -> None:
    by_id = {t.id: t for t in tickets}
    lines = ["# Eval report", "", "_Generated by `python -m triage.evaluate`. Narrative analysis is in README.md._", ""]
    lines += ["## Metrics", "", "| metric | value |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in metrics.items()]
    lines += ["", "## Run", "", "| stat | value |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in run_stats.items()]
    lines += ["", "## Category confusion (labeled subset)", "", _confusion(results, labels, "category", CATEGORIES)]
    lines += ["## Priority confusion (labeled subset)", "", _confusion(results, labels, "priority", PRIORITIES)]

    lines += ["## Labeled tickets", "", "| id | gold cat | pred cat | gold pri | pred pri | conf | esc | source | flags |",
              "|---|---|---|---|---|---|---|---|---|"]
    for r in results:
        if r.id not in labels:
            continue
        g = labels[r.id]
        c = r.category if r.category == g["category"] else f"**{r.category}** ✗"
        p = r.priority if r.priority == g["priority"] else f"**{r.priority}** ✗"
        lines.append(f"| {r.id} | {g['category']} | {c} | {g['priority']} | {p} | {r.confidence:.2f} | "
                     f"{'yes' if r.escalate else ''} | {r.source} | {', '.join(r.flags)} |")

    lines += ["", "## Unlabeled tickets (spot-check by hand)", "", "| id | subject | cat | pri | conf | esc | flags |",
              "|---|---|---|---|---|---|---|"]
    for r in results:
        if r.id in labels:
            continue
        subj = (by_id[r.id].subject or by_id[r.id].body[:40] or "(empty)").replace("|", "/")
        lines.append(f"| {r.id} | {subj} | {r.category} | {r.priority} | {r.confidence:.2f} | "
                     f"{'yes' if r.escalate else ''} | {', '.join(r.flags)} |")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    settings = load_settings()
    tickets = load_tickets(settings.tickets_path)
    labels = load_labels(settings.labels_path)
    model = OpenAICompatibleModel(settings)
    log.info("Triaging %d tickets with %s at %s (concurrency=%d)", len(tickets), settings.llm_model,
             settings.llm_base_url, settings.concurrency)

    t0 = time.perf_counter()
    done = Counter()

    def progress(r: TriageResult):
        done["n"] += 1
        log.info("[%2d/%d] %s -> %s/%s conf=%.2f src=%s%s", done["n"], len(tickets), r.id, r.category,
                 r.priority, r.confidence, r.source, f" flags={r.flags}" if r.flags else "")

    results = run_batch(tickets, model, settings, on_done=progress)
    elapsed = time.perf_counter() - t0

    metrics = compute_metrics(results, labels)
    sources = Counter(r.source for r in results)
    run_stats = {
        "model": settings.llm_model,
        "llm_calls": model.calls,
        "llm_successful_calls": model.successes,
        "tickets_needing_retry": sum(r.attempts > 1 for r in results),
        **{f"source_{k}": v for k, v in sorted(sources.items())},
        "wall_time_s": round(elapsed, 1),
        "mean_latency_ms": int(sum(r.latency_ms for r in results) / len(results)) if results else 0,
    }

    out = settings.results_path
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps({"metrics": metrics, "predictions": [r.public() for r in results]},
                              indent=2, ensure_ascii=False), encoding="utf-8")
    (out.parent / "details.json").write_text(
        json.dumps({"run": run_stats, "predictions": [r.model_dump() for r in results]}, indent=2, ensure_ascii=False),
        encoding="utf-8")
    write_report(out.parent / "report.md", results, labels, metrics, run_stats, tickets)

    print("\n=== Eval ===")
    for k, v in {**metrics, **run_stats}.items():
        print(f"  {k:36s} {v}")
    print(f"\nWrote {out} ({len(results)} predictions), details.json and report.md")

    needs_model = sum(1 for r in results if r.source != "rule_shortcut")
    if needs_model and model.successes == 0:
        print(f"\nERROR: the model never answered ({settings.llm_base_url}). Predictions are rule-based "
              "fallbacks only - this is not a real eval.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
